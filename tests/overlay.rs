/// The two things an example cannot show, because an example is one call site
/// and these differ *between* call sites.
#[test]
fn an_optional_position_is_written_only_when_something_after_it_is() {
    let build = |body: &str| {
        let mut diags = Diagnostics::new();
        let source = format!(
            "attributes {{ outFile = \"a.exe\" }}\n\
             installer {{ section(\"Core\", function()\n\
             local f = fileOpen(INSTDIR .. \"/log.txt\", \"r\")\n\
             {body}\n\
             f:close()\n\
             end), }}"
        );
        installua::build(&source, &mut diags)
            .unwrap_or_else(|| panic!("{}", diags.render("<test>")))
    };

    // The output is optional, so a call nobody reads writes no register. A
    // temporary here would be correct NSIS and would still enter the clobber
    // set, costing a caller a save for a value that was never wanted.
    let discarded = build("f:seek(0, \"END\")");
    assert!(
        discarded.contains("FileSeek $0 0 \"END\"\n"),
        "an unread optional output should not be emitted:\n{discarded}"
    );

    // And `mode` is optional but *precedes* the output, so reading the result
    // means writing a mode the author never named — `FileSeek $0 0 $1` is not
    // an option, NSIS reads `$1` as the mode and rejects the line.
    let filled = build("local p = f:seek(0)\ndetailPrint(\"at \" .. p)");
    assert!(
        filled.contains("FileSeek $0 0 SET $1\n"),
        "reaching the output should fill `mode`:\n{filled}"
    );

    // Same position, same row, nothing after it: not written.
    let bare = build("f:seek(0)");
    assert!(
        bare.contains("FileSeek $0 0\n"),
        "a trailing optional stays absent:\n{bare}"
    );
}

/// Optional positions are named, and naming one writes every position before it.
///
/// This is the rule an example cannot show either, because an example is one
/// call site and the point is which *other* call sites are now writable.
/// `createShortcut` is the case that motivated it: setting the description used
/// to mean writing all nine arguments, four of which the author does not care
/// about and three of which are enums they would have to look up.
#[test]
fn an_optional_position_is_reached_by_name_and_fills_the_ones_before_it() {
    let build = |body: &str| {
        let mut diags = Diagnostics::new();
        let source = format!(
            "attributes {{ outFile = \"a.exe\" }}\n\
             installer {{ section(\"Core\", function()\n\
             {body}\n\
             end), }}"
        );
        installua::build(&source, &mut diags)
            .unwrap_or_else(|| panic!("{}", diags.render("<test>")))
    };

    // The last option, and the five before it are the compiler's problem.
    // `iconIndex`'s `0` is one argument rather than two: `-CMDHELP` prints
    // `icon index`, and that is one NSIS argument whose name has a space in it.
    let comment = build(
        "createShortcut(DESKTOP .. \"/App.lnk\", INSTDIR .. \"/app.exe\", \
         { comment = \"Launch App\" })",
    );
    assert!(
        comment.contains(
            "CreateShortcut \"$DESKTOP\\App.lnk\" \"$INSTDIR\\app.exe\" \"\" \"\" 0 \
             SW_SHOWNORMAL \"\" \"Launch App\"\n"
        ),
        "reaching `comment` should fill the five positions before it:\n{comment}"
    );

    // Nothing named: nothing filled. The two required positions are the line.
    let bare = build("createShortcut(DESKTOP .. \"/App.lnk\", INSTDIR .. \"/app.exe\")");
    assert!(
        bare.contains("CreateShortcut \"$DESKTOP\\App.lnk\" \"$INSTDIR\\app.exe\"\n"),
        "an unnamed option stays absent:\n{bare}"
    );

    // A leading optional, which is what counting could never do: `"open"` is
    // the first *required* position, so it can only mean `verb`.
    let shell = build("execShell(\"open\", \"https://example.invalid\", { invokeIdList = true })");
    assert!(
        shell.contains("ExecShell /INVOKEIDLIST \"open\" \"https://example.invalid\"\n"),
        "a toggle is spelled by the compiler and placed by the table:\n{shell}"
    );

    // And `false` is the absence rather than a token, so it emits nothing.
    let off = build("execShell(\"open\", \"https://example.invalid\", { invokeIdList = false })");
    assert!(
        off.contains("ExecShell \"open\" \"https://example.invalid\"\n"),
        "`false` is not a flag:\n{off}"
    );
}

/// The other half of the options table: the flags, which were never positions.
#[test]
fn a_flag_is_reached_by_name_and_placed_by_the_table() {
    let build = |body: &str| {
        let mut diags = Diagnostics::new();
        let source = format!(
            "attributes {{ outFile = \"a.exe\" }}\n\
             installer {{ section(\"Core\", function()\n\
             {body}\n\
             end), }}"
        );
        installua::build(&source, &mut diags)
            .unwrap_or_else(|| panic!("{}", diags.render("<test>")))
    };

    // `/r` is what NSIS calls it and `recursive` is what it does. Both flags in
    // one table, in the snapshot's order rather than the caller's.
    let both = build("rmDir(INSTDIR, { rebootOk = true, recursive = true })");
    assert!(
        both.contains("RMDir /r /REBOOTOK $INSTDIR\n"),
        "flags are emitted in table order, not the order they were written:\n{both}"
    );

    // `false` is the absence rather than a token, exactly as it is for a toggle.
    let off = build("rmDir(INSTDIR, { recursive = false })");
    assert!(
        off.contains("RMDir $INSTDIR\n"),
        "`false` is not a flag:\n{off}"
    );

    // `Opt::after` is a place in the emitted line and not an argument index:
    // `/SHORT` goes in front of the *output* register, which no counting of the
    // caller's arguments could have worked out.
    let short = build("local full = getFullPathName(INSTDIR, { short = true })\ndetailPrint(full)");
    assert!(
        short.contains("GetFullPathName /SHORT $0 $INSTDIR\n"),
        "a flag can precede an output:\n{short}"
    );

    // Both halves of the table on one row: `sizeInKb` is an unambiguous
    // trailing optional and stays an argument, and the flags never were one.
    let copy =
        build("copyFiles(INSTDIR .. \"/data\", INSTDIR .. \"/backup\", 100, { silent = true })");
    assert!(
        copy.contains("CopyFiles /SILENT \"$INSTDIR\\data\" \"$INSTDIR\\backup\" 100\n"),
        "a counted optional and a named flag coexist:\n{copy}"
    );

    // And the flag nobody writes. `WriteRegMultiStr` without `/REGEDIT5` is an
    // error rather than a different instruction, so the compiler supplies it.
    let multi = build("writeRegMultiStr(HKLM, \"Software/Example\", \"List\", \"660000000000\")");
    assert!(
        multi.contains("WriteRegMultiStr /REGEDIT5 HKLM \"Software\\Example\" \"List\""),
        "a required flag is written without being named:\n{multi}"
    );
}

/// A flag that carries a value, in the two shapes the table has for it.
///
/// `File`'s `/x` is a list because it repeats, and `MessageBox`'s `/SD` is a
/// field of §15.18's own table because its value has to be an answer the
/// buttons beside it can give. Neither is a position, and neither is a `bool`.
#[test]
fn a_flag_can_carry_a_value() {
    let build = |body: &str| {
        let mut diags = Diagnostics::new();
        let source = format!(
            "attributes {{ outFile = \"a.exe\" }}\n\
             installer {{ section(\"Core\", function()\n\
             {body}\n\
             end), }}"
        );
        installua::build(&source, &mut diags)
            .unwrap_or_else(|| panic!("{}", diags.render("<test>")))
    };

    // One `/x` per element, in the order they were written, each a path: §5's
    // `/` → `\` applies to an exclusion as much as to the filespec it excludes.
    let excluded = build(
        "file(\"assets/icon.ico\", { recursive = true, exclude = { \"build/*.tmp\", \"*.log\" } })",
    );
    assert!(
        excluded.contains("File /r /x \"build\\*.tmp\" /x \"*.log\" \"assets\\icon.ico\"\n"),
        "a list is one flag per element:\n{excluded}"
    );

    // An empty list is no flag at all, the way `false` is.
    let none = build("file(\"assets/icon.ico\", { exclude = {} })");
    assert!(
        none.contains("File \"assets\\icon.ico\"\n"),
        "an empty list writes nothing:\n{none}"
    );

    // `/SD` follows the text, which is where `Opt::after` says it goes, and the
    // answer is spelled the way `messageBox` returns it rather than as `IDNO`.
    let silent =
        build("messageBox { text = \"Restart?\", buttons = \"YESNO\", silentAnswer = \"NO\" }");
    assert!(
        silent.contains("MessageBox MB_YESNO \"Restart?\" /SD IDNO\n"),
        "the silent answer is written where NSIS wants it:\n{silent}"
    );
}

/// The two errors a valued flag can give that a `bool` one cannot.
#[test]
fn a_valued_flag_says_what_it_wants() {
    let errors = |body: &str| {
        let mut diags = Diagnostics::new();
        let source = format!(
            "attributes {{ outFile = \"a.exe\" }}\n\
             installer {{ section(\"Core\", function()\n\
             {body}\n\
             end), }}"
        );
        let built = installua::build(&source, &mut diags);
        assert!(built.is_none() || diags.has_errors(), "{body} was accepted");
        diags.render("<test>")
    };

    // Not a `bool`, so "on or off" would be the wrong sentence.
    let scalar = errors("file(\"assets/icon.ico\", { exclude = \"*.tmp\" })");
    assert!(
        scalar.contains("`exclude` is a list") && scalar.contains("`/x` for each"),
        "{scalar}"
    );

    // An answer this dialog cannot give. NSIS accepts `/SD IDYES` under
    // `MB_OKCANCEL` and the silent install then takes a branch nobody wrote,
    // which is exactly why the check is here and not there.
    let impossible =
        errors("messageBox { text = \"Go?\", buttons = \"OKCANCEL\", silentAnswer = \"YES\" }");
    assert!(
        impossible.contains("`OKCANCEL` cannot answer `YES`")
            && impossible.contains("`OK`, `CANCEL`"),
        "{impossible}"
    );
}

