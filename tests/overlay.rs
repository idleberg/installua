fn makensis() -> Option<String> {
    let name = std::env::var("MAKENSIS").unwrap_or_else(|_| "makensis".to_string());
    Command::new(&name)
        .arg("-VERSION")
        .output()
        .ok()
        .filter(|output| output.status.success())
        .map(|_| name)
}

/// Regenerates the golden and the source beside it. Ignored, because a test
/// that rewrites its own expectation is not a test.
#[test]
#[ignore = "regenerates tests/golden/overlay-examples.{lua,nsi}"]
fn write_the_golden() {
    let source = program();
    let mut diags = Diagnostics::new();
    let built = installua::build(&source, &mut diags)
        .unwrap_or_else(|| panic!("{}", diags.render("overlay.lua")));

    std::fs::write("tests/golden/overlay-examples.lua", source).unwrap();
    std::fs::write("tests/golden/overlay-examples.nsi", built).unwrap();

    let source = attribute_program();
    let mut diags = Diagnostics::new();
    let built = installua::build(&source, &mut diags)
        .unwrap_or_else(|| panic!("{}", diags.render("overlay-attributes.lua")));

    std::fs::write("tests/golden/overlay-attributes.lua", source).unwrap();
    std::fs::write("tests/golden/overlay-attributes.nsi", built).unwrap();
}
