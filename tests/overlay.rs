//! §14's example pairs: every `Exposed` row emits, and the emission is a
//! golden.
//!
//! *"The granular Installua→NSIS assembly tests should not be hand-written per
//! instruction; they should be impossible to omit."* So the example lives on
//! the overlay row, the census requires one on every `Exposed` row, and this
//! file compiles all of them into a single `.nsi` diffed by exact equality.
//!
//! One program with one section per row, rather than one program per row: the
//! section body **is** the smallest region containing the behaviour, so the
//! golden reads as a table of what each name emits and a wrong lowering shows
//! up as three changed lines rather than as a changed file.
//!
//! This is the mechanism PLAN's Phase 6 depends on. "One overlay row plus its
//! mandatory example pair" is only data entry if the *mandatory* half is
//! enforced; otherwise it is a debate about whether this one needs a test.

use std::path::Path;
use std::process::Command;

use installua::diag::Diagnostics;
use installua::table::{self, Class};

/// The whole exposed surface, as one installer.
fn program() -> String {
    let mut source = String::from(
        "-- Generated by tests/overlay.rs from the overlay's own examples.\n\
         attributes {\n\
         \tname = \"Overlay examples\",\n\
         \toutFile = \"examples.exe\",\n\
         \tunicode = true,\n\
         }\n\n\
         installer {\n",
    );

    for (name, example) in examples() {
        source.push_str(&format!("\tsection(\"{name}\", function()\n"));
        for line in example.lines() {
            source.push_str(&format!("\t\t{line}\n"));
        }
        source.push_str("\tend),\n");
    }

    // `WriteUninstaller` with no uninstaller is *"Error: no Uninstall section
    // specified"* — a whole-script fact, not a per-line one, so no example can
    // carry it and the program has to. This is the first thing tier 3 caught,
    // and it had been in the golden since the day the row was written.
    source.push_str(
        "}\n\nuninstaller {\n\tsection(\"Uninstall\", function()\n\t\trmDir(INSTDIR)\n\tend),\n}\n",
    );
    source
}

/// One `(section name, example)` per `Exposed` row, in `-CMDHELP` order.
///
/// Keyed on the NSIS name rather than the Installua one because two rows can
/// share an Installua name — `writeReg` is `WriteRegStr` and `WriteRegDWORD` —
/// and both dispatches need their own example.
fn examples() -> Vec<(&'static str, &'static str)> {
    table::overlay::ROWS
        .iter()
        .filter(|row| row.class == Class::Exposed)
        .filter_map(|row| row.example.map(|example| (row.nsis, example)))
        .collect()
}

/// Every `Attribute` row, set to a value derived from its own [`Setting`].
///
/// An attribute needs no hand-written example the way an `Exposed` row does,
/// and that is the point of batch 10: the row *is* the example, because
/// `Setting` says what the field holds and the snapshot says which keywords an
/// enum accepts. A row that lies about either produces a line `makensis`
/// rejects, which is the tier-3 half below.
fn attribute_program() -> String {
    let mut source = String::from(
        "-- Generated by tests/overlay.rs from the overlay's own `Attribute` rows.\n\
         attributes {\n",
    );

    for entry in table::table() {
        let table::Class::Attribute(holds) = entry.class else {
            continue;
        };
        let Some(field) = entry.installua else {
            continue;
        };
        // The dotted ones are `versionInfo`'s and are written through it; the
        // rest of `Handled` is hand-shaped and has no value this can guess.
        if field.contains('.') || matches!(holds, table::Setting::Handled(_)) {
            continue;
        }

        let value = match holds {
            // `Icon` and `LicenseData` open the file at compile time, so these
            // two want a real one — see tests/fixtures/README.md.
            table::Setting::Str { path: true } if field == "icon" => {
                "\"assets/icon.ico\"".to_string()
            }
            table::Setting::Str { path: true } if field == "license" => {
                "\"assets/license.txt\"".to_string()
            }
            // Two settings take a *shaped* string — `major.minor` and
            // `maj.min.bld.rev` — and [`table::Setting::Str`] says only "a
            // string". The narrowing is real and the table cannot state it, so
            // the compiler does not check it either: `peSubsysVer = "hello"`
            // reaches `makensis` and is rejected there. The values are here
            // rather than in the row because a row is not an example.
            table::Setting::Str { path: false } if field == "peSubsysVer" => "\"5.1\"".to_string(),
            table::Setting::Str { path: false } if field == "manifestMaxVersionTested" => {
                "\"10.0.19041.0\"".to_string()
            }
            table::Setting::Str { path: true } => format!("\"{field}.out\""),
            table::Setting::Str { path: false } => format!("\"{field}\""),
            table::Setting::Bool { .. } => "true".to_string(),
            table::Setting::Int => "1".to_string(),
            // The first keyword the snapshot lists — a value chosen by the
            // table rather than by whoever wrote this test.
            table::Setting::Enum => format!(
                "\"{}\"",
                entry
                    .params
                    .first()
                    .and_then(|param| param.members().first())
                    .unwrap_or_else(|| panic!("`{field}` is an enum with no members"))
            ),
            table::Setting::Handled(_) => unreachable!("filtered above"),
        };
        source.push_str(&format!("\t{field} = {value},\n"));
    }

    source.push_str(
        "}\n\ninstaller {\n\tsection(\"Core\", function()\n\
         \t\tdetailPrint(\"installing\")\n\tend),\n}\n",
    );
    source
}

