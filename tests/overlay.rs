//! §14's example pairs: every `Exposed` row emits, and the emission is a
//! golden.
//!
//! *"The granular Installua→NSIS assembly tests should not be hand-written per
//! instruction; they should be impossible to omit."* So the example lives on
//! the overlay row, the census requires one on every `Exposed` row, and this
//! file compiles all of them into a single `.nsi` diffed by exact equality.
//!
//! One program with one section per row, rather than one program per row: the
//! section body **is** the smallest region containing the behaviour, so the
//! golden reads as a table of what each name emits and a wrong lowering shows
//! up as three changed lines rather than as a changed file.
//!
//! This is the mechanism PLAN's Phase 6 depends on. "One overlay row plus its
//! mandatory example pair" is only data entry if the *mandatory* half is
//! enforced; otherwise it is a debate about whether this one needs a test.

use std::path::Path;
use std::process::Command;

use installua::diag::Diagnostics;
use installua::table::{self, Class};

/// The whole exposed surface, as one installer.
fn program() -> String {
    // The two things a row can be reached through rather than called: a section
    // handle and the block's install types (§13). Neither is an argument, so
    // neither can live in an example — the example writes `handle.text` and the
    // program is what makes `handle` a section the block lists.
    //
    // `brandingImage` is here for the same reason one level down: `SetBrandingImage`
    // writes into a control the *script* has to have asked for, and `makensis`
    // rejects the whole program with "no branding image found in chosen UI"
    // when it has not. An attribute is not an argument either.
    let mut source = String::from(
        "-- Generated by tests/overlay.rs from the overlay's own examples.\n\
         attributes {\n\
         \tname = \"Overlay examples\",\n\
         \toutFile = \"examples.exe\",\n\
         \tunicode = true,\n\
         \tbrandingImage = { edge = \"top\", size = \"20u\" },\n\
         }\n\n\
         local handle = section(\"Addressed\", function()\n\
         \tdetailPrint(\"the section the examples below address\")\n\
         end)\n\n\
         installer {\n\
         \tinstallTypes = { \"Full\", \"Minimal\" },\n\
         \thandle,\n",
    );

    for (name, example) in examples() {
        source.push_str(&format!("\tsection(\"{name}\", function()\n"));
        for line in example.lines() {
            source.push_str(&format!("\t\t{line}\n"));
        }
        source.push_str("\tend),\n");
    }

    // `WriteUninstaller` with no uninstaller is *"Error: no Uninstall section
    // specified"* — a whole-script fact, not a per-line one, so no example can
    // carry it and the program has to. This is the first thing tier 3 caught,
    // and it had been in the golden since the day the row was written.
    source.push_str(
        "}\n\nuninstaller {\n\tsection(\"Uninstall\", function()\n\t\trmDir(INSTDIR)\n\tend),\n}\n",
    );
    source
}

/// One `(section name, example)` per `Exposed` row, in `-CMDHELP` order.
///
/// Keyed on the NSIS name rather than the Installua one because two rows can
/// share an Installua name — `writeReg` is `WriteRegStr` and `WriteRegDWORD` —
/// and both dispatches need their own example.
fn examples() -> Vec<(&'static str, &'static str)> {
    table::overlay::ROWS
        .iter()
        .filter(|row| row.class == Class::Exposed)
        .filter_map(|row| row.example.map(|example| (row.nsis, example)))
        .collect()
}

/// Every `Attribute` row, set to a value derived from its own [`Setting`].
///
/// An attribute needs no hand-written example the way an `Exposed` row does,
/// and that is the point of batch 10: the row *is* the example, because
/// `Setting` says what the field holds and the snapshot says which keywords an
/// enum accepts. A row that lies about either produces a line `makensis`
/// rejects, which is the tier-3 half below.
fn attribute_program() -> String {
    let mut source = String::from(
        "-- Generated by tests/overlay.rs from the overlay's own `Attribute` rows.\n\
         attributes {\n",
    );

    for entry in table::table() {
        let table::Class::Attribute(holds) = entry.class else {
            continue;
        };
        let Some(field) = entry.installua else {
            continue;
        };
        // The dotted ones are `versionInfo`'s and are written through it; the
        // rest of `Handled` is hand-shaped and has no value this can guess.
        if field.contains('.') || matches!(holds, table::Setting::Handled(_)) {
            continue;
        }
        if EXCLUSIVE.contains(&entry.nsis) {
            continue;
        }

        // A position the snapshot repeats takes a list of what one value is.
        // One element for the same reason a [`table::Setting::Each`] gets one:
        // the golden is here to prove the shape emits, and that two become two
        // is [`a_repeating_position_fills_one_line`].
        let value = derived(entry, 0, field, holds);
        let value = match entry.params.first() {
            Some(param) if param.repeats() => format!("{{ {value} }}"),
            _ => value,
        };
        source.push_str(&format!("\t{field} = {value},\n"));
    }

    source.push_str(
        "}\n\ninstaller {\n\tsection(\"Core\", function()\n\
         \t\tdetailPrint(\"installing\")\n\tend),\n}\n",
    );
    source
}

/// The Lua a field of this shape can be written with, derived from the shape.
///
/// `index` is the position the value stands against, which only an enum reads:
/// a part of a table is the same question one position along, which is why this
/// is one recursive function and not a second copy for parts.
fn derived(entry: &table::Instruction, index: usize, field: &str, holds: table::Setting) -> String {
    if let Some((_, _, real)) = REAL
        .iter()
        .find(|(nsis, part, _)| *nsis == entry.nsis && *part == field)
    {
        return (*real).to_string();
    }

    match holds {
        // `Icon` and `LicenseData` open the file at compile time, so these
        // two want a real one — see tests/fixtures/README.md.
        table::Setting::Str { path: true } if field == "icon" => "\"assets/icon.ico\"".to_string(),
        table::Setting::Str { path: true } if field == "license" => {
            "\"assets/license.txt\"".to_string()
        }
        // Two settings take a *shaped* string — `major.minor` and
        // `maj.min.bld.rev` — and [`table::Setting::Str`] says only "a
        // string". The narrowing is real and the table cannot state it, so
        // the compiler does not check it either: `peSubsysVer = "hello"`
        // reaches `makensis` and is rejected there. The values are here
        // rather than in the row because a row is not an example.
        table::Setting::Str { path: false } if field == "peSubsysVer" => "\"5.1\"".to_string(),
        table::Setting::Str { path: false } if field == "manifestMaxVersionTested" => {
            "\"10.0.19041.0\"".to_string()
        }
        table::Setting::Str { path: true } => format!("\"{field}.out\""),
        table::Setting::Str { path: false } => format!("\"{field}\""),
        table::Setting::Bool { .. } => "true".to_string(),
        table::Setting::Int => "1".to_string(),
        // The first keyword the snapshot lists — a value chosen by the table
        // rather than by whoever wrote this test. Written *bare* when that
        // keyword is also a sigil-less constant, because a registry root is
        // `HKCR` and not `"HKCR"` (§15.1), and derived from the same two tables
        // so that both spellings are compiled here rather than one.
        table::Setting::Enum => {
            let member = entry
                .params
                .get(index)
                .and_then(|param| param.members().first())
                .unwrap_or_else(|| panic!("`{field}` is an enum with no members"));
            match installua::builtins::constant_named(member) {
                Some(constant) if !constant.sigil => (*member).to_string(),
                _ => format!("\"{member}\""),
            }
        }
        table::Setting::Table(parts) => {
            let parts: Vec<String> = parts
                .iter()
                .enumerate()
                .map(|(offset, part)| {
                    format!(
                        "{} = {}",
                        part.field,
                        derived(entry, index + offset, part.field, part.holds)
                    )
                })
                .collect();
            format!("{{ {} }}", parts.join(", "))
        }
        // One element, because the point of the golden is that the shape emits
        // and not that it emits twice — and because two `PERemoveResource`
        // lines naming the same resource is an error the second time. That a
        // list of two becomes two lines is [`a_repeating_setting_repeats`].
        table::Setting::Each(one) => format!("{{ {} }}", derived(entry, index, field, *one)),
        table::Setting::Handled(_) => unreachable!("filtered above"),
    }
}

/// The parts whose value has to be a real one, and the only hand-written data in
/// this file.
///
/// [`table::Setting::Str`] says "a string" and NSIS means less than that here: a
/// resource type is `#N` or a name it knows, `PEAddResource` opens the file at
/// compile time, `PERemoveResource` names a resource that must already be in the
/// stub, and a manifest path is an XPath rooted at `/`. Every one of those is a
/// narrowing the table cannot state, which is why they are examples rather than
/// rows — the same reason `peSubsysVer`'s `"5.1"` is below.
const REAL: &[(&str, &str, &str)] = &[
    ("PEAddResource", "file", "\"assets/icon.ico\""),
    ("PEAddResource", "restype", "\"#100\""),
    ("PEAddResource", "resname", "\"#1\""),
    ("PEAddResource", "reslang", "\"1033\""),
    // `#5` is `RT_DIALOG` and `#105` one of the stub's own, which is the only
    // resource this test can be sure exists.
    ("PERemoveResource", "restype", "\"#5\""),
    ("PERemoveResource", "resname", "\"#105\""),
    ("PERemoveResource", "reslang", "\"ALL\""),
    ("ManifestAppendCustomString", "path", "\"/assembly\""),
    // `(height|width)` in the snapshot is a metavariable and not a pair of
    // keywords: NSIS reads a number here, suffixed `u` for dialog units. Both
    // parts carry the suffix because NSIS requires them to agree — `top 20u 2`
    // is *Invalid number!* — and a bare number is *Must use dialog units on
    // non-Win32 platforms!*, so `u` is the only form this test can assemble.
    ("AddBrandingImage", "size", "\"20u\""),
    ("AddBrandingImage", "padding", "\"2u\""),
    // Not a narrowing but a *pair*: `compressorDictSize` is read only under
    // LZMA, and NSIS says so — `warning 8026: compressor is not set to LZMA.
    // Effectively ignored.` — which `-WX` turns into a failure. The first
    // keyword the snapshot lists is `zlib`, so this test has to name the
    // compressor its own dictionary size implies. The dependency is real for
    // authors too and is deferred to `makensis`, which states it by name.
    ("SetCompressor", "compressor", "\"lzma\""),
];

/// Attributes that cannot appear in the one derived program, because another
/// attribute in it excludes them.
///
/// One entry, and it is a genuine pair rather than a gap in the machinery:
/// `SetCompressorDictSize` warns unless the compressor is LZMA (8026) and
/// `SetCompressionLevel` warns when it *is* (8025), so under `-WX` no single
/// script can carry both. The one left out is covered by
/// [`compression_level_assembles_against_a_compressor_that_reads_it`], because
/// skipping it here must not mean skipping it.
const EXCLUSIVE: &[&str] = &["SetCompressionLevel"];

