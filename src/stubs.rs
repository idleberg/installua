/// The top-level `attributes {}` fields and their Lua types.
///
/// Derived from the census: every `Attribute` row whose field path is a plain
/// name. The nested ones (`versionInfo.product`) are the `VersionInfo` class
/// above, which is why the dot is in the overlay and not in a second list.
fn attribute_fields() -> Vec<(&'static str, String)> {
    table::table()
        .iter()
        .filter_map(|entry| match entry.class {
            Class::Attribute(holds) => Some((entry, entry.installua?, holds)),
            _ => None,
        })
        .filter(|(_, field, _)| !field.contains('.'))
        .map(|(entry, field, holds)| (field, setting_type(entry, field, holds)))
        .chain([("versionInfo", "installua.VersionInfo".to_string())])
        .collect()
}

/// The Lua type of one attribute, which is the row's [`table::Setting`] and
/// nothing else. An enum becomes the alias generated above, which is what makes
/// its members complete rather than merely legal.
///
/// A [`table::Setting::Table`] becomes an inline table type rather than a named
/// class: the parts are the field's own and are named nowhere else, so a class
/// would be a name the user has to learn in order to write a literal they were
/// going to write anyway. Its enum parts are keyed on the *parameter*, matching
/// the alias [`alias_table`] emits for them.
fn setting_type(entry: &table::Instruction, field: &str, holds: table::Setting) -> String {
    let ty = bare_type(entry, field, holds);
    // A repeating position takes a list of one value, the same way a repeating
    // *line* takes a list of one line. That the two spell alike in Lua and
    // differently in NSIS is the point: a caller writes what the field holds
    // and never learns which kind of repetition it is.
    match entry.params.first() {
        Some(param) if param.repeats() => format!("{ty}[]"),
        _ => ty,
    }
}

/// The type of one value of the field, before the snapshot is asked whether the
/// position it stands against repeats.
fn bare_type(entry: &table::Instruction, field: &str, holds: table::Setting) -> String {
    match holds {
        table::Setting::Bool { .. } => "boolean".to_string(),
        table::Setting::Int => "integer".to_string(),
        table::Setting::Enum => alias_of(field),
        table::Setting::Str { .. } => "string".to_string(),
        table::Setting::Handled(ty) => ty.to_string(),
        table::Setting::Table(parts) => {
            let parts: Vec<String> = parts
                .iter()
                .enumerate()
                .map(|(index, part)| {
                    let ty = match part.holds {
                        table::Setting::Enum => entry
                            .params
                            .get(index)
                            .map(|param| alias_of(param.shape.name))
                            .unwrap_or_else(|| "string".to_string()),
                        other => bare_type(entry, part.field, other),
                    };
                    let optional = entry
                        .params
                        .get(index)
                        .is_some_and(|param| !param.required());
                    format!("{}{}: {ty}", part.field, if optional { "?" } else { "" })
                })
                .collect();
            format!("{{ {} }}", parts.join(", "))
        }
        // A list of whatever one line takes. The brackets go on the outside
        // because the repetition is of the *line*, which is the whole of what
        // the inner type describes.
        table::Setting::Each(one) => format!("{}[]", bare_type(entry, field, *one)),
    }
}

